#!/usr/bin/env bash
# Generate (or rotate) the password of every NATS user and the bcrypt hash
# file the servers load.
#
#   scripts/credentials.sh                    create missing passwords only
#   scripts/credentials.sh --rotate USER      new password for USER
#   scripts/credentials.sh --rotate-all       new passwords for everyone
#
# Then reload the servers (no restart): docker compose kill -s SIGHUP nats-1 nats-2 nats-3
# and hand the new password to the application owning that user.
#
# Files (gitignored, 0600, directory 0700):
#   secrets/users/<user>.password      plaintext password, 64 hex chars: give
#                                      it to the application owning <user>
#   secrets/server/credentials.conf    bcrypt hashes (cost 11) referenced by
#                                      config/accounts.conf; servers only
SCRIPT_NAME=credentials
# shellcheck source=scripts/lib.sh source-path=SCRIPTDIR
. "$(dirname "$0")/lib.sh"
require_cmd openssl docker

# Keep in sync with config/accounts.conf.
NATS_USERS="sys-admin app-admin orders-publisher orders-consumer"

ROTATE=" "
while [ $# -gt 0 ]; do
  case "$1" in
    --rotate)
      [ $# -ge 2 ] || die "--rotate needs a user name"
      case " $NATS_USERS " in *" $2 "*) ;; *) die "unknown user: $2 (known: $NATS_USERS)" ;; esac
      ROTATE="$ROTATE$2 "
      shift
      ;;
    --rotate-all) ROTATE=" $NATS_USERS " ;;
    -h | --help)
      sed -n '2,18p' "$0"
      exit 0
      ;;
    *) die "unknown argument: $1" ;;
  esac
  shift
done

SECRETS_DIR="$NATS_DIR/secrets"
CONF="$SECRETS_DIR/server/credentials.conf"
umask 077
mkdir -p "$SECRETS_DIR/users" "$SECRETS_DIR/server"
chmod 700 "$SECRETS_DIR" "$SECRETS_DIR/users" "$SECRETS_DIR/server"

var_name() { printf '%s_PASSWORD_HASH' "$(printf '%s' "$1" | tr 'a-z-' 'A-Z_')"; }

changed=0
for user in $NATS_USERS; do
  file="$SECRETS_DIR/users/$user.password"
  case "$ROTATE" in *" $user "*) rotate=1 ;; *) rotate=0 ;; esac
  if [ "$rotate" = 1 ] || [ ! -s "$file" ]; then
    # In-place write keeps the inode stable for Compose bind mounts.
    # No trailing newline: applications can use the file content verbatim.
    printf '%s' "$(openssl rand -hex 32)" >"$file"
    chmod 600 "$file"
    log "$user: new password written to secrets/users/$user.password"
    changed=1
  fi
done

if [ "$changed" = 0 ] && [ -s "$CONF" ]; then
  missing=0
  for user in $NATS_USERS; do
    grep -q "^$(var_name "$user"):" "$CONF" || missing=1
  done
  if [ "$missing" = 0 ]; then
    log "credentials unchanged (use --rotate USER or --rotate-all to rotate)"
    exit 0
  fi
fi

# bcrypt all passwords in one throwaway nats-box container: no network, the
# passwords travel over stdin only (never argv or environment of this host).
image="$(service_image nats-box)"
[ -n "$image" ] || die "could not resolve the nats-box image from docker-compose.yaml"
hashes="$(
  for user in $NATS_USERS; do
    tr -d '\r\n' <"$SECRETS_DIR/users/$user.password"
    echo
  done | docker run --rm -i --network none --entrypoint /bin/sh "$image" -c \
    'while IFS= read -r p; do PASSWORD="$p" nats server passwd --cost 11 </dev/null || exit 1; done'
)" || die "bcrypt hashing failed"

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
{
  echo "# GENERATED by scripts/credentials.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Do not edit, do not commit."
  echo "# bcrypt hashes of secrets/users/*.password, referenced by config/accounts.conf."
  i=1
  for user in $NATS_USERS; do
    hash="$(printf '%s\n' "$hashes" | sed -n "${i}p")"
    # shellcheck disable=SC2016 # literal bcrypt prefixes
    case "$hash" in '$2a$'* | '$2b$'*) ;; *) die "unexpected bcrypt output for $user" ;; esac
    printf '%s: "%s"\n' "$(var_name "$user")" "$hash"
    i=$((i + 1))
  done
} >"$tmp"
cat "$tmp" >"$CONF"
chmod 600 "$CONF"
log "wrote secrets/server/credentials.conf"

if [ -n "$(compose ps -q nats-1 nats-2 nats-3 2>/dev/null || true)" ]; then
  log "running servers detected; apply with: docker compose kill -s SIGHUP nats-1 nats-2 nats-3"
fi
